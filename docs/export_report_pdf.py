from pathlib import Path
from xml.sax.saxutils import escape

from docx import Document
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, PageBreak, Image, Table, TableStyle,
    KeepTogether,
)

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'ClassifyAI_AG_News_Classifier_Report.docx'
OUTPUT = ROOT / 'ClassifyAI_AG_News_Classifier_Report.pdf'
docx = Document(SOURCE)

NAVY = colors.HexColor('#12304A')
TEAL = colors.HexColor('#087E83')
INK = colors.HexColor('#2D3748')
PALE = colors.HexColor('#F0F6F8')
ACCENT = colors.HexColor('#E8F5F5')

styles = getSampleStyleSheet()
styles.add(ParagraphStyle(name='BodyCustom', parent=styles['BodyText'], fontName='Helvetica', fontSize=8.7, leading=12.2, textColor=INK, spaceAfter=5.5, alignment=TA_LEFT))
styles.add(ParagraphStyle(name='TitleCustom', parent=styles['Title'], fontName='Helvetica-Bold', fontSize=31, leading=36, textColor=NAVY, alignment=TA_CENTER, spaceAfter=12))
styles.add(ParagraphStyle(name='H1Custom', parent=styles['Heading1'], fontName='Helvetica-Bold', fontSize=19, leading=23, textColor=NAVY, spaceBefore=9, spaceAfter=8, keepWithNext=True))
styles.add(ParagraphStyle(name='H2Custom', parent=styles['Heading2'], fontName='Helvetica-Bold', fontSize=12.2, leading=15, textColor=TEAL, spaceBefore=8, spaceAfter=4, keepWithNext=True))
styles.add(ParagraphStyle(name='H3Custom', parent=styles['Heading3'], fontName='Helvetica-Bold', fontSize=10, leading=12, textColor=colors.HexColor('#31566F'), spaceBefore=6, spaceAfter=3, keepWithNext=True))
styles.add(ParagraphStyle(name='CaptionCustom', parent=styles['BodyText'], fontName='Helvetica-Oblique', fontSize=7.4, leading=9, textColor=colors.HexColor('#5A6978'), alignment=TA_CENTER, spaceAfter=8))
styles.add(ParagraphStyle(name='SmallCell', parent=styles['BodyText'], fontName='Helvetica', fontSize=7, leading=9, textColor=INK, spaceAfter=0))
styles.add(ParagraphStyle(name='SmallCellHead', parent=styles['BodyText'], fontName='Helvetica-Bold', fontSize=7, leading=9, textColor=colors.white, spaceAfter=0))
styles.add(ParagraphStyle(name='CoverCenter', parent=styles['BodyText'], fontName='Helvetica', fontSize=12, leading=17, alignment=TA_CENTER, textColor=INK, spaceAfter=8))
styles.add(ParagraphStyle(name='CoverSmall', parent=styles['BodyText'], fontName='Helvetica', fontSize=9.5, leading=13, alignment=TA_CENTER, textColor=INK, spaceAfter=6))
styles.add(ParagraphStyle(name='BulletCustom', parent=styles['BodyCustom'], leftIndent=14, firstLineIndent=-8, bulletIndent=2, spaceAfter=3))
styles.add(ParagraphStyle(name='NumberCustom', parent=styles['BodyCustom'], leftIndent=16, firstLineIndent=-12, spaceAfter=3))
styles.add(ParagraphStyle(name='BoxCustom', parent=styles['BodyText'], fontName='Helvetica', fontSize=8.5, leading=11, textColor=colors.HexColor('#164E63'), spaceAfter=0))

def xml_text(text):
    # Keep basic emphasis generated by python-docx; escape all text safely.
    return escape(text).replace('\n', '<br/>')

def add_page_number(canvas, doc):
    canvas.saveState()
    w, h = A4
    if doc.page > 1:
        canvas.setFont('Helvetica', 7)
        canvas.setFillColor(colors.HexColor('#647382'))
        canvas.drawRightString(w - .65*inch, h - .36*inch, 'CLASSIFYAI  |  AG NEWS CLASSIFICATION STUDY')
    canvas.setFont('Helvetica', 7)
    canvas.setFillColor(colors.HexColor('#647382'))
    canvas.drawCentredString(w/2, .34*inch, f'Continuous Assessment 2  •  INT234  •  {doc.page}')
    canvas.restoreState()

def make_table(data):
    converted=[]
    for ri,row in enumerate(data):
        converted.append([Paragraph(xml_text(str(cell)), styles['SmallCellHead'] if ri == 0 else styles['SmallCell']) for cell in row])
    tbl=Table(converted, repeatRows=1, hAlign='CENTER', splitByRow=1)
    cmds=[('VALIGN',(0,0),(-1,-1),'MIDDLE'),('GRID',(0,0),(-1,-1),.35,colors.HexColor('#D7E1E8')),('LEFTPADDING',(0,0),(-1,-1),5),('RIGHTPADDING',(0,0),(-1,-1),5),('TOPPADDING',(0,0),(-1,-1),4),('BOTTOMPADDING',(0,0),(-1,-1),4),('BACKGROUND',(0,0),(-1,0),NAVY)]
    for ri in range(1,len(data)):
        if ri%2: cmds.append(('BACKGROUND',(0,ri),(-1,ri),PALE))
    tbl.setStyle(TableStyle(cmds))
    return tbl

story=[]
paras=docx.paragraphs
tables=docx.tables
inline=iter(docx.inline_shapes)
table_iter=iter(tables)
image_index=0

# Preserve the report's paragraph/table order by walking document body XML.
from docx.oxml.ns import qn
body=docx._element.body
for child in body.iterchildren():
    if child.tag == qn('w:p'):
        from docx.text.paragraph import Paragraph as DocxParagraph
        p=DocxParagraph(child, docx)
        text=p.text.strip()
        # Paragraph may contain a figure; add the embedded picture before its caption.
        has_drawing=bool(child.xpath('.//w:drawing'))
        if has_drawing:
            shape=next(inline)
            blob=shape._inline.graphic.graphicData.pic.blipFill.blip.embed
            image_part=docx.part.related_parts[blob]
            image_index += 1
            import io
            from PIL import Image as PILImage
            pil=PILImage.open(io.BytesIO(image_part.blob))
            iw,ih=pil.size
            maxw=6.35*inch; maxh=7.7*inch
            scale=min(maxw/iw,maxh/ih)
            story.append(Image(io.BytesIO(image_part.blob), width=iw*scale, height=ih*scale))
            story.append(Spacer(1,4))
            continue
        if not text:
            continue
        st=p.style.name if p.style else 'Normal'
        if text == '\x0c':
            story.append(PageBreak()); continue
        if st == 'Title':
            story.append(Paragraph(xml_text(text),styles['TitleCustom']))
        elif st.startswith('Heading 1'):
            story.append(Paragraph(xml_text(text),styles['H1Custom']))
        elif st.startswith('Heading 2'):
            story.append(Paragraph(xml_text(text),styles['H2Custom']))
        elif st.startswith('Heading 3'):
            story.append(Paragraph(xml_text(text),styles['H3Custom']))
        elif st == 'Caption Custom':
            story.append(Paragraph(xml_text(text),styles['CaptionCustom']))
        elif st == 'List Bullet':
            story.append(Paragraph('•&nbsp;&nbsp;'+xml_text(text),styles['BulletCustom']))
        elif st == 'List Number':
            story.append(Paragraph(xml_text(text),styles['NumberCustom']))
        elif 'CONTINUOUS ASSESSMENT 2' == text:
            story.append(Spacer(1,1.0*inch)); story.append(Paragraph(xml_text(text),ParagraphStyle('TopLine',parent=styles['CoverCenter'],fontName='Helvetica-Bold',fontSize=15,textColor=TEAL,spaceAfter=18)))
        elif text.startswith('A comparative study'):
            story.append(Paragraph(xml_text(text),styles['CoverSmall']))
        elif text.startswith('CHAPTER '):
            story.append(PageBreak()); story.append(Spacer(1,2.2*inch)); story.append(Paragraph(xml_text(text),ParagraphStyle('ChapterLabel',parent=styles['CoverCenter'],fontName='Helvetica-Bold',fontSize=12,textColor=TEAL)))
        elif text.startswith('A report on'):
            story.append(Paragraph(xml_text(text),styles['CoverSmall']))
        elif text.startswith('Academic Project Report'):
            story.append(Paragraph(xml_text(text),styles['CoverSmall']))
        elif text.startswith('Student:') or text.startswith('Signature:'):
            story.append(Paragraph(xml_text(text),styles['CoverSmall']))
        elif text.startswith('Figure '):
            story.append(Paragraph(xml_text(text),styles['CaptionCustom']))
        elif text.startswith('•'):
            story.append(Paragraph(xml_text(text),styles['BulletCustom']))
        else:
            # Preserve bold runs in ordinary paragraphs.
            chunks=[]
            for run in p.runs:
                value=xml_text(run.text)
                if not value: continue
                if run.bold: value=f'<b>{value}</b>'
                if run.italic: value=f'<i>{value}</i>'
                chunks.append(value)
            story.append(Paragraph(''.join(chunks) if chunks else xml_text(text),styles['BodyCustom']))
    elif child.tag == qn('w:tbl'):
        t=next(table_iter)
        data=[[cell.text.replace('\n',' / ') for cell in row.cells] for row in t.rows]
        story.append(Spacer(1,4)); story.append(make_table(data)); story.append(Spacer(1,7))

pdf=SimpleDocTemplate(str(OUTPUT),pagesize=A4,rightMargin=.68*inch,leftMargin=.68*inch,topMargin=.62*inch,bottomMargin=.58*inch,title=docx.core_properties.title,author=docx.core_properties.author,subject=docx.core_properties.subject)
pdf.build(story,onFirstPage=add_page_number,onLaterPages=add_page_number)
print(f'{OUTPUT} | figures={image_index} | story_items={len(story)}')
